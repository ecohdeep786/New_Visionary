import { readFileSync, writeFileSync, mkdtempSync, rmSync, realpathSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const backend = join(root, 'backend/upstream/backend');
const schema = readFileSync(join(backend, 'prisma/schema.prisma'), 'utf8');
const marker = '// DATA-01 domain schema starts here.';
if (schema.split(marker).length !== 2) throw Error('Unique domain schema marker required.');
const evolved = existsSync(join(backend, 'prisma/migrations/20261102000002_data_04_invitation_reissue/migration.sql'));
if (evolved && process.argv.includes('--write')) throw Error('Versioned domain history is immutable. Add a reviewed migration; never rewrite DATA-01 from the current model.');
const temporary = mkdtempSync(join(tmpdir(), 'visionary-domain-ddl-'));
try {
  const target = join(temporary, 'domain.prisma');
  writeFileSync(target, 'datasource db {\n provider = "postgresql"\n url = env("DATABASE_URL")\n}\n' + schema.split(marker)[1]);
  const cli = process.env.PRISMA_CLI_PATH || join(backend, 'node_modules/prisma/build/index.js');
  const output = spawnSync(process.execPath, [cli, 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', target, '--script'], {
    cwd: backend, encoding: 'utf8', windowsHide: true,
    env: { ...process.env, DATABASE_URL: 'postgresql://synthetic:synthetic@127.0.0.1:1/visionary_data_test_never_connected' },
  });
  if (output.error || output.status !== 0) throw Error(output.stderr || String(output.error));
  // Prisma cannot express these partial indexes. Keep the deliberate PostgreSQL
  // constraints here, generated alongside the canonical model DDL, never in a
  // separate migration registry or runtime schema copy.
  const extra = '\n-- Explicit PostgreSQL-only domain invariants\n' +
    'CREATE UNIQUE INDEX "workspaces_personal_uid_key" ON "workspaces" ("uid") WHERE "isPersonal";\n' +
    'CREATE UNIQUE INDEX "consent_grants_account_scope_key" ON "consent_grants" ("uid", "purpose", "consentVersion") WHERE "resourceId" IS NULL;\n' +
    'ALTER TABLE "command_results" ADD CONSTRAINT "command_results_revision_positive" CHECK ("revision" > 0);\n';
  const ddl = '-- Generated by scripts/domain-ddl.mjs from the DATA-01 Prisma models.\n' + output.stdout.replace(/\r\n/g, '\n').trim() + '\n' + extra;
  const migration = join(backend, 'prisma/migrations/20261024000001_data_01_workspaces/migration.sql');
  if (!evolved) {
    if (process.argv.includes('--write')) writeFileSync(migration, ddl);
    else if (readFileSync(migration, 'utf8').replace(/\r\n/g, '\n') !== ddl) throw Error('Domain DDL drift: run node scripts/domain-ddl.mjs --write and review the change.');
    console.log('PASS: canonical domain DDL matches Prisma models and explicit constraints.');
  } else {
    // Verify current models against the actual replayed version chain. A current
    // model cannot be compared to, or written over, the historical v1 artifact.
    const raw = process.env.DATA_TEST_DATABASE_URL;
    if (!raw) throw Error('Versioned DDL verification requires data:check and its disposable local SQL target.');
    const base = new URL(raw);
    if (!['localhost', '127.0.0.1', '[::1]'].includes(base.hostname) || !/^\/visionary_data_test(?:_|$)/.test(base.pathname)) throw Error('Synthetic DDL database boundary required.');
    const req = createRequire(join(backend, 'package.json'));
    const { PrismaClient } = req('@prisma/client');
    const { canonicalMigrations } = req('./dist/src/data/migration-registry.js');
    const admin = new PrismaClient({ datasources: { db: { url: raw } } });
    const namespace = 'ddl_' + randomUUID().replaceAll('-', '');
    const url = new URL(base); url.searchParams.set('schema', namespace);
    const db = new PrismaClient({ datasources: { db: { url: String(url) } } });
    try {
      await admin.$executeRawUnsafe('CREATE SCHEMA "' + namespace + '"');
      await db.$transaction(async tx => {
        for (const version of canonicalMigrations(backend)) for (const statement of version.statements) await tx.$executeRawUnsafe(statement);
      }, { timeout: 15000 });
      const actual = spawnSync(process.execPath, [cli, 'migrate', 'diff', '--from-schema-datasource', target,
        '--to-schema-datamodel', target, '--exit-code', '--script'], { cwd: backend, encoding: 'utf8', windowsHide: true,
        env: { ...process.env, DATABASE_URL: String(url) } });
      if (actual.error || actual.status !== 0) throw Error('Versioned physical domain/model drift: ' + (actual.stdout || actual.stderr || actual.error));
      // Prisma does not express these partial indexes/checks. Inspect the real
      // native invariants too; DATA-01/DATA-04 exercise their failure semantics.
      const indexes = await db.$queryRawUnsafe(`SELECT c.relname AS name,t.relname AS table,am.amname AS method,
        i.indisunique AS "isUnique",i.indisvalid AS valid,i.indisready AS ready,i.indnatts AS attributes,
        ARRAY(SELECT pg_get_indexdef(i.indexrelid,k,true) FROM generate_series(1,i.indnkeyatts) k ORDER BY k) AS keys,
        pg_get_expr(i.indpred,i.indrelid) AS predicate FROM pg_index i
        JOIN pg_class c ON c.oid=i.indexrelid JOIN pg_class t ON t.oid=i.indrelid
        JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_am am ON am.oid=c.relam
        WHERE n.nspname=$1`, namespace);
      const compact = sql => String(sql ?? '').replaceAll('"', '').replaceAll(namespace + '.', '').replace(/[\s()[\]]/g, '');
      for (const [name, table, keys, predicate] of [
        ['workspaces_personal_uid_key', 'workspaces', ['uid'], 'isPersonal'],
        ['consent_grants_account_scope_key', 'consent_grants', ['uid', 'purpose', 'consentVersion'], 'resourceId IS NULL'],
        ['invitations_one_pending_email', 'invitations', ['workspaceId', 'lower(email)'], "status = ANY (ARRAY['PENDING'::InvitationStatus,'ISSUED'::InvitationStatus])"],
      ]) {
        const index = indexes.find(i => i.name === name);
        if (!index || index.table !== table || index.method !== 'btree' || !index.isUnique || !index.valid || !index.ready ||
            index.attributes !== keys.length || JSON.stringify(index.keys.map(compact)) !== JSON.stringify(keys.map(compact)) ||
            compact(index.predicate) !== compact(predicate)) throw Error('Native domain index drift: ' + name);
      }
      const constraints = await db.$queryRawUnsafe('SELECT pg_get_constraintdef(c.oid) AS definition FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace WHERE n.nspname=$1 AND c.conname=$2', namespace, 'command_results_revision_positive');
      if (constraints.length !== 1 || compact(constraints[0].definition) !== 'CHECKrevision>0') throw Error('Native positive revision constraint drift.');
      console.log('PASS: replayed versioned domain DDL matches current Prisma models and native invariants.');
    } finally {
      await db.$disconnect();
      if (!/^ddl_[a-f0-9]{32}$/.test(namespace)) throw Error('Owned DDL schema cleanup boundary mismatch.');
      await admin.$executeRawUnsafe('DROP SCHEMA IF EXISTS "' + namespace + '" CASCADE');
      await admin.$disconnect();
    }
  }
} finally {
  const actual = realpathSync(temporary);
  if (dirname(actual) !== realpathSync(tmpdir()) || !basename(actual).startsWith('visionary-domain-ddl-')) throw Error('Temporary DDL cleanup boundary mismatch.');
  rmSync(actual, { recursive: true });
}
