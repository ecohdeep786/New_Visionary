import { readFileSync, writeFileSync, mkdtempSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const backend = join(root, 'backend/upstream/backend');
const schema = readFileSync(join(backend, 'prisma/schema.prisma'), 'utf8');
const marker = '// DATA-01 domain schema starts here.';
if (schema.split(marker).length !== 2) throw Error('Unique domain schema marker required.');
const temporary = mkdtempSync(join(tmpdir(), 'visionary-domain-ddl-'));
try {
  const target = join(temporary, 'domain.prisma');
  writeFileSync(target, 'datasource db {\n provider = "postgresql"\n url = env("DATABASE_URL")\n}\n' + schema.split(marker)[1]);
  const cli = process.env.PRISMA_CLI_PATH || join(backend, 'node_modules/prisma/build/index.js');
  const output = spawnSync(process.execPath, [cli, 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', target, '--script'], {
    cwd: backend, encoding: 'utf8', windowsHide: true,
    env: { ...process.env, DATABASE_URL: 'postgresql://synthetic:synthetic@127.0.0.1:1/visionary_data_test_never_connected' },
  });
  if (output.error || output.status !== 0) throw Error(output.stderr || String(output.error));
  // Prisma cannot express these partial indexes. Keep the deliberate PostgreSQL
  // constraints here, generated alongside the canonical model DDL, never in a
  // separate migration registry or runtime schema copy.
  const extra = '\n-- Explicit PostgreSQL-only domain invariants\n' +
    'CREATE UNIQUE INDEX "workspaces_personal_uid_key" ON "workspaces" ("uid") WHERE "isPersonal";\n' +
    'CREATE UNIQUE INDEX "consent_grants_account_scope_key" ON "consent_grants" ("uid", "purpose", "consentVersion") WHERE "resourceId" IS NULL;\n' +
    'ALTER TABLE "command_results" ADD CONSTRAINT "command_results_revision_positive" CHECK ("revision" > 0);\n';
  const ddl = '-- Generated by scripts/domain-ddl.mjs from the DATA-01 Prisma models.\n' + output.stdout.replace(/\r\n/g, '\n').trim() + '\n' + extra;
  const migration = join(backend, 'prisma/migrations/20261024000001_data_01_workspaces/migration.sql');
  if (process.argv.includes('--write')) writeFileSync(migration, ddl);
  else if (readFileSync(migration, 'utf8').replace(/\r\n/g, '\n') !== ddl) throw Error('Domain DDL drift: run node scripts/domain-ddl.mjs --write and review the change.');
  console.log('PASS: canonical domain DDL matches Prisma models and explicit constraints.');
} finally {
  const actual = realpathSync(temporary);
  if (dirname(actual) !== realpathSync(tmpdir()) || !basename(actual).startsWith('visionary-domain-ddl-')) throw Error('Temporary DDL cleanup boundary mismatch.');
  rmSync(actual, { recursive: true });
}
