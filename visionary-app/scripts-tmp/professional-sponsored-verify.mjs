import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';

const base = process.env.VISIONARY_BASE || 'http://127.0.0.1:4191';
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--no-proxy-server'] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
await context.addInitScript(() => {
 if (localStorage.getItem('visionary_workspace_v2')) return;
 const users = [
  { id: 'sponsor-pro', email: 'sam@sponsor.test', full_name: 'Sam', identity: 'professional', roles: ['professional'], age_band: 'adult', onboarding_complete: true },
  { id: 'sponsor-org', email: 'company@sponsor.test', full_name: 'Company admin', org_name: 'Example Company', identity: 'organization', roles: ['organization'], age_band: 'adult', onboarding_complete: true },
 ];
 const empty = () => ({ conversations: [], sessions: [], artifacts: [], resources: [], notifications: [], audit: [], preferences: { locale: 'en', interfaceLocale: 'en', voice: false, memory: true }, subscription: { plan: 'Free', state: 'active', invoices: [], usage: 0, usageDay: new Date().toISOString().slice(0, 10) }, legacyImported: false });
 localStorage.setItem('visionary_users', JSON.stringify(users));
 localStorage.setItem('visionary_sessions', JSON.stringify(users.map(user => ({ token: user.id, userId: user.id, email: user.email, expiresAt: Date.now() + 86400000, createdAt: Date.now() }))));
 localStorage.setItem('visionary_session_token', 'sponsor-pro');
 localStorage.setItem('visionary_workspace_v2', JSON.stringify({ version: 2, people: users.map(user => ({ id: user.id, email: user.email, name: user.full_name, ageBand: user.age_band, roles: user.roles })), workspaces: users.map(user => ({ id: `${user.id}:${user.identity}`, personId: user.id, role: user.identity, name: user.identity, lastPath: '/dashboard/home' })), active: Object.fromEntries(users.map(user => [user.id, `${user.id}:${user.identity}`])), relationships: [], data: Object.fromEntries(users.map(user => [`${user.id}:${user.identity}`, empty()])) }));
});
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
const enter = async (token, path) => { await page.evaluate(value => localStorage.setItem('visionary_session_token', value), token); await page.goto(`${base}${path}`, { waitUntil: 'networkidle' }); };
try {
 await page.goto(`${base}/dashboard/career`, { waitUntil: 'networkidle' });
 await page.getByText('Personal professional workspace').waitFor();
 await page.getByLabel('Capability or role target').fill('Personal data career');
 await page.getByLabel('What would useful progress look like?').fill('PRIVATE_PERSONAL_GOAL');
 await page.getByRole('button', { name: 'Save direction' }).click();
 await page.getByRole('status').getByText(/Career target saved/).waitFor();
 await enter('sponsor-org', '/dashboard/connections');
 await page.getByLabel('Visionary account email').fill('sam@sponsor.test');
 await page.getByLabel('Workspace role').selectOption('professional');
 await page.getByRole('button', { name: 'Request connection' }).click();
 await page.getByText('Organization membership · professional').waitFor();
 await page.getByText('Local action history').click();
 await page.getByText('company@sponsor.test · requested').waitFor();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/organization-invite-pending-390.png' });
 await enter('sponsor-pro', '/dashboard/connections');
 await page.getByText('Needs your approval').waitFor();
 await page.getByRole('button', { name: 'Accept' }).click();
 await page.getByRole('article').getByText('Connected', { exact: true }).waitFor();
 await page.getByText('Local action history').click();
 await page.getByText('sam@sponsor.test · accepted').waitFor();
 await page.goto(`${base}/dashboard/career`, { waitUntil: 'networkidle' });
 const switcher = page.getByRole('combobox', { name: 'Active workspace' });
 const options = await switcher.locator('option').allTextContents();
 assert.ok(options.some(label => /Personal.*professional/i.test(label)));
 assert.ok(options.some(label => /Work.*Example Company/.test(label)));
 await switcher.selectOption('sponsor-pro:professional:org:company@sponsor.test');
 await page.goto(`${base}/dashboard/career`, { waitUntil: 'networkidle' });
 await page.getByText('Company learning space').waitFor();
 assert.equal(await page.getByLabel('What would useful progress look like?').inputValue(), '');
 await page.getByLabel('Capability or role target').fill('Company analysis target');
 await page.getByLabel('What would useful progress look like?').fill('WORK_ONLY_GOAL');
 await page.getByRole('button', { name: 'Save direction' }).click();
 await page.getByRole('status').getByText(/Career target saved/).waitFor();
 await page.getByText('Company learning space').scrollIntoViewIfNeeded();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/professional-sponsored-work-390.png' });
 await switcher.selectOption('sponsor-pro:professional');
 await page.goto(`${base}/dashboard/career`, { waitUntil: 'networkidle' });
 await page.getByText('Your personal professional space').waitFor();
 assert.equal(await page.getByLabel('Capability or role target').inputValue(), 'Personal data career');
 assert.equal(await page.getByLabel('What would useful progress look like?').inputValue(), 'PRIVATE_PERSONAL_GOAL');
 await page.getByText('Your personal professional space').scrollIntoViewIfNeeded();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/professional-personal-boundary-390.png' });
 await enter('sponsor-org', '/dashboard/connections');
 await page.getByRole('button', { name: 'Disconnect' }).click();
 await page.getByText('Closed · revoked').waitFor();
 await page.getByText('Local action history').click();
 await page.getByText('company@sponsor.test · revoked').waitFor();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/organization-invite-revoked-390.png' });
 await page.goto(`${base}/dashboard/audit`, { waitUntil: 'networkidle' });
 await page.getByRole('heading', { name: 'Organization audit' }).waitFor();
 await page.getByLabel('Action source').selectOption('membership');
 await page.getByText('Membership · requested', { exact: true }).waitFor();
 await page.getByText('Membership · accepted', { exact: true }).waitFor();
 await page.getByText('Membership · revoked', { exact: true }).waitFor();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/organization-audit-390.png' });
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
 await page.goto(`${base}/dashboard/notifications`, { waitUntil: 'networkidle' });
 await page.getByRole('heading', { name: 'Organization updates' }).waitFor();
 assert.equal(await page.getByText('Current connection: revoked', { exact: true }).count(), 3);
 await page.getByRole('button', { name: 'Mark read', exact: true }).first().click();
 await page.getByRole('status').getByText('Update marked read on this device.').waitFor();
 await page.getByLabel('Show updates').selectOption('unread');
 assert.equal(await page.getByText('Current connection: revoked', { exact: true }).count(), 2);
 await page.reload({ waitUntil: 'networkidle' });
 await page.getByLabel('Show updates').selectOption('unread');
 assert.equal(await page.getByText('Current connection: revoked', { exact: true }).count(), 2);
 await page.getByRole('heading', { name: 'Membership history' }).scrollIntoViewIfNeeded();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/organization-updates-390.png' });
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
 await page.getByRole('link', { name: 'Review connection' }).first().click();
 await page.waitForFunction(() => document.activeElement?.id?.startsWith('organization-invite-'));
 assert.equal(await page.getByRole('button', { name: 'Accept', exact: true }).count(), 0);
 await enter('sponsor-pro', '/dashboard/career');
 await page.getByText('Your personal professional space').waitFor();
 assert.equal(await page.getByLabel('Capability or role target').inputValue(), 'Personal data career');
 assert.equal(await page.getByRole('combobox', { name: 'Active workspace' }).count(), 0);
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
 assert.deepEqual(errors, []);
 console.log('Professional sponsored journey: audited invite, accept, separate personal/work goals, switch, revoke and personal recovery passed at 390px.');
} finally { await browser.close(); }
