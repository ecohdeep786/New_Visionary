// Fictional professional → organization portfolio sharing journey.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const base=process.env.VISIONARY_BASE||'http://127.0.0.1:4191';
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--no-proxy-server']});
const context=await browser.newContext({viewport:{width:390,height:844}});
await context.addInitScript(()=>{
 if(localStorage.getItem('visionary_workspace_v2'))return;
 const users=[{id:'share-pro',email:'sam@share.test',full_name:'Sam',identity:'professional',roles:['professional'],age_band:'adult',onboarding_complete:true},{id:'share-org',email:'org@share.test',full_name:'Company admin',identity:'organization',roles:['organization'],age_band:'adult',onboarding_complete:true}];
 const empty=()=>({conversations:[],sessions:[],artifacts:[],resources:[],notifications:[],audit:[],preferences:{locale:'en',interfaceLocale:'en',lowBandwidth:false,notifications:'weekly',memory:true,voice:false},subscription:{plan:'Free',state:'active',invoices:[],usage:0,usageDay:'2026-09-29'},legacyImported:false});
 localStorage.setItem('visionary_users',JSON.stringify(users));
 localStorage.setItem('visionary_sessions',JSON.stringify(users.map(user=>({token:user.identity,userId:user.id,email:user.email,expiresAt:Date.now()+86400000,createdAt:Date.now()}))));
 localStorage.setItem('visionary_session_token','professional');
 localStorage.setItem('visionary_workspace_v2',JSON.stringify({version:2,people:users.map(user=>({id:user.id,email:user.email,name:user.full_name,ageBand:'adult',roles:user.roles})),workspaces:users.map(user=>({id:`${user.id}:${user.identity}`,personId:user.id,role:user.identity,name:user.identity,lastPath:'/dashboard/home'})),active:Object.fromEntries(users.map(user=>[user.id,`${user.id}:${user.identity}`])),relationships:[{id:'company-connection',from:'share-org',to:'share-pro',type:'organization',scope:['shared-resources'],status:'active'}],data:{'share-pro:professional':empty(),'share-org:organization':empty()}}));
});
const page=await context.newPage();page.setDefaultNavigationTimeout(120000);
const errors=[];page.on('pageerror',error=>errors.push(String(error)));
const enter=async role=>{await page.evaluate(value=>localStorage.setItem('visionary_session_token',value),role);await page.goto(`${base}/dashboard/build`,{waitUntil:'networkidle'});};
try{
 await page.goto(`${base}/dashboard/build`,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'New project'}).click();
 await page.getByLabel('Project title').fill('Decision report');
 await page.getByLabel('Your working document').fill('First reviewed copy for the company.');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await page.getByRole('button',{name:'Share',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Accepted connection').selectOption('share-org');
 await dialog.getByText('Copy to share with Company admin').waitFor();
 await dialog.getByText('First reviewed copy for the company.').waitFor();
 await page.screenshot({path:'docs/visionary/baseline/design-2026-09-27/professional-share-preview-390.png'});
 await dialog.getByRole('button',{name:'Confirm sharing'}).click();
 await enter('organization');
 await page.getByRole('heading',{name:'Shared with me'}).waitFor();
 await page.getByText('Decision report · Sam').click();
 await page.getByText('First reviewed copy for the company.').waitFor();
 await page.goto(`${base}/dashboard/home`,{waitUntil:'networkidle'});
 await page.getByText(/Learning totals are hidden for groups or concepts with fewer than 5/).waitFor();
 await page.getByText(/Learning totals are hidden for groups or concepts with fewer than 5/).evaluate(node=>node.scrollIntoView({block:'center'}));
 await page.screenshot({path:'docs/visionary/baseline/design-2026-09-27/organization-small-group-390.png'});
 await enter('professional');
 await page.getByRole('button',{name:/Decision report/}).click();
 await page.getByLabel('Your working document').fill('Second private revision.');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 await enter('organization');
 await page.getByText('Decision report · Sam').click();
 await page.getByText('First reviewed copy for the company.').waitFor();
 assert.equal(await page.getByText('Second private revision.').count(),0);
 await enter('professional');
 await page.getByRole('button',{name:/Decision report/}).click();
 await page.getByRole('button',{name:'Share',exact:true}).click();
 await page.getByRole('dialog').getByLabel('Accepted connection').selectOption('share-org');
 await page.getByRole('dialog').getByText('Second private revision.').waitFor();
 await page.getByRole('dialog').getByRole('button',{name:'Confirm sharing'}).click();
 await enter('organization');
 await page.getByText('Decision report · Sam').click();
 await page.getByText('Second private revision.').waitFor();
 await page.getByText('Second private revision.').evaluate(node=>node.scrollIntoView({block:'center'}));
 await page.screenshot({path:'docs/visionary/baseline/design-2026-09-27/organization-received-copy-390.png'});
 await page.evaluate(()=>{const db=JSON.parse(localStorage.getItem('visionary_workspace_v2'));db.relationships[0].status='revoked';localStorage.setItem('visionary_workspace_v2',JSON.stringify(db));window.dispatchEvent(new CustomEvent('visionary:v2-change'));});
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.getByRole('heading',{name:'Shared with me'}).count(),0);
 await enter('professional');
 await page.getByRole('button',{name:/Decision report/}).waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 assert.deepEqual(errors,[]);
 console.log('PASS: exact professional share preview, fixed recipient copy, explicit re-share, organization revocation and retained personal artifact; zero page errors/overflow.');
}finally{await browser.close();}
