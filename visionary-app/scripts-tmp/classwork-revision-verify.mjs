// Fictional production-preview journey: reviewed lesson through revision and return.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const base = process.env.VISIONARY_BASE || 'http://127.0.0.1:4191';
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--no-proxy-server'] });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
await context.addInitScript(() => {
 if (localStorage.getItem('visionary_workspace_v2')) return;
 const users = ['teacher', 'student'].map(identity => ({ id: `revision-${identity}`, email: `${identity}@revision.test`, full_name: identity === 'teacher' ? 'Dev' : 'Aarav', identity, roles: [identity], age_band: 'adult', onboarding_complete: true }));
 const empty = { conversations: [], sessions: [], artifacts: [], resources: [], notifications: [], audit: [], preferences: { locale: 'en', interfaceLocale: 'en', lowBandwidth: false, notifications: 'weekly', memory: true, voice: false }, subscription: { plan: 'Free', state: 'active', invoices: [], usage: 0, usageDay: '2026-09-28' }, legacyImported: false };
 localStorage.setItem('visionary_users', JSON.stringify(users));
 localStorage.setItem('visionary_sessions', JSON.stringify(users.map(user => ({ token: user.identity, userId: user.id, email: user.email, expiresAt: Date.now() + 86400000, createdAt: Date.now() }))));
 localStorage.setItem('visionary_session_token', 'teacher');
 localStorage.setItem('visionary_workspace_v2', JSON.stringify({ version: 2, people: users.map(user => ({ id: user.id, email: user.email, name: user.full_name, ageBand: 'adult', roles: user.roles })), workspaces: users.map(user => ({ id: `${user.id}:${user.identity}`, personId: user.id, role: user.identity, name: user.identity, lastPath: '/dashboard/home' })), active: Object.fromEntries(users.map(user => [user.id, `${user.id}:${user.identity}`])), relationships: [], data: Object.fromEntries(users.map(user => [`${user.id}:${user.identity}`, empty])) }));
 localStorage.setItem('visionary_entity_Classroom', JSON.stringify([{ id: 'revision-class', name: 'Reasoning together', subject: 'Mathematics', teacher_email: users[0].email, teacher_id: users[0].id, teacher_name: 'Dev', join_code: 'REVISION', color: '#1967d2' }]));
 localStorage.setItem('visionary_entity_Enrollment', JSON.stringify([{ id: 'revision-enrollment', class_id: 'revision-class', student_email: users[1].email, student_id: users[1].id, student_name: 'Aarav', status: 'active' }]));
});
const page = await context.newPage();
page.setDefaultNavigationTimeout(120000);
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
const switchRole = async (role, route) => {
 await page.evaluate(role => localStorage.setItem('visionary_session_token', role), role);
 await page.goto(`${base}${route}`, { waitUntil: 'networkidle' });
};
const openReview = async () => {
 await switchRole('teacher', '/dashboard/class/revision-class');
 await page.getByRole('button', { name: 'Classwork', exact: true }).click();
 await page.getByRole('button', { name: /^Review/ }).click();
 await page.getByRole('dialog').waitFor();
};
try {
 await page.goto(`${base}/dashboard/prepare`, { waitUntil: 'networkidle' });
 await page.getByRole('button', { name: 'New lesson' }).click();
 const editor = page.getByRole('dialog').first();
 await editor.getByLabel('Title', { exact: true }).fill('Explain volume');
 await editor.getByLabel('Outline and notes').fill('Explain the count of unit cubes.');
 await editor.getByRole('button', { name: 'Add question' }).click();
 await editor.getByRole('textbox', { name: 'Question 1', exact: true }).fill('Why do three dimensions matter?');
 await editor.getByLabel('Status').selectOption('reviewed');
 await editor.getByRole('button', { name: 'Save draft' }).click();
 await page.getByRole('button', { name: /Explain volume/ }).first().click();
 await page.getByRole('button', { name: 'Assign reviewed lesson' }).click();
 const assign = page.getByRole('dialog').last();
 await assign.getByLabel('Class').selectOption({ index: 1 });
 await assign.getByRole('button', { name: 'Confirm assignment' }).click();
 await page.getByText('Assigned. A reviewed copy is now available').first().waitFor();
 await switchRole('student', '/dashboard/classes?class=revision-class');
 await page.getByLabel('1. Why do three dimensions matter?').fill('Layers count cubes.');
 await page.getByRole('button', { name: 'Submit', exact: true }).click();
 await page.getByText('Submitted — waiting for your teacher to review.').waitFor();
 await openReview();
 await page.getByText(/Saved lesson version:/).waitFor();
 await page.getByRole('button', { name: 'Request revision', exact: true }).click();
 await page.getByRole('alert').filter({ hasText: 'Explain what the learner should revise.' }).waitFor();
 await page.getByLabel('Feedback for Aarav').fill('Explain rows, columns and cubic units.');
 await page.getByRole('button', { name: 'Request revision', exact: true }).click();
 await page.getByText('Attempt 1 · Revision requested', { exact: true }).waitFor();
 await switchRole('student', '/dashboard/classes?class=revision-class');
 await page.getByText('Revision requested · Attempt 1', { exact: true }).waitFor();
 assert.equal(await page.getByLabel('1. Why do three dimensions matter?').inputValue(), 'Layers count cubes.');
 await page.getByLabel('1. Why do three dimensions matter?').fill('Three layers of nine cubes make 27 cubic units.');
 await page.reload({ waitUntil: 'networkidle' });
 assert.match(await page.getByLabel('1. Why do three dimensions matter?').inputValue(), /27 cubic units/);
 await page.getByText('Revision requested · Attempt 1', { exact: true }).scrollIntoViewIfNeeded();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/student-classwork-revision-390.png' });
 await page.getByRole('button', { name: 'Resubmit', exact: true }).click();
 await page.getByText('Submitted — waiting for your teacher to review.').waitFor();
 await openReview();
 await page.getByText('Attempt 2', { exact: true }).waitFor();
 await page.getByLabel('Grade for Aarav').fill('9');
 await page.getByLabel('Feedback for Aarav').fill('Clear reasoning with cubic units.');
 await page.getByRole('button', { name: 'Return', exact: true }).click();
 await page.getByText('Returned', { exact: true }).waitFor();
 await page.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/teacher-classwork-return-390.png' });
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
 await switchRole('student', '/dashboard/classes?class=revision-class');
 await page.getByText('Clear reasoning with cubic units.', { exact: true }).waitFor();
 await page.getByText('Previous attempts and feedback (1)', { exact: true }).click();
 await page.getByText('Feedback: Explain rows, columns and cubic units.', { exact: true }).waitFor();
 const record = await page.evaluate(() => JSON.parse(localStorage.getItem('visionary_entity_Submission'))[0]);
 assert.equal(record.attempt, 2); assert.equal(record.grade, 9); assert.equal(record.revision_history.length, 1);
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
 assert.deepEqual(errors, []);
 console.log('PASS: authored assignment → submission → required revision feedback → saved revised draft → resubmit → teacher return → learner history; zero page errors or mobile overflow.');
} finally { await browser.close(); }
