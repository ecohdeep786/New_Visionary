const { chromium } = await import('playwright-core');
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--no-proxy-server'] });
const base = 'http://127.0.0.1:4188';
const errors = [];
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
await context.addInitScript(`(() => {
 const learner = { id: 'demo-learner', email: 'learner@visionary.test', full_name: 'Aarav', identity: 'student', onboarding_complete: true, age_band: 'minor', roles: ['student'] };
 const parent = { id: 'demo-parent', email: 'parent@visionary.test', full_name: 'Anika', identity: 'parent', onboarding_complete: true, age_band: 'adult', roles: ['parent'] };
 localStorage.setItem('visionary_users', JSON.stringify([learner, parent]));
 localStorage.setItem('visionary_sessions', JSON.stringify([{ token: 'learner-connection-qa', userId: learner.id, email: learner.email, expiresAt: Date.now() + 86400000, createdAt: Date.now() }, { token: 'parent-connection-qa', userId: parent.id, email: parent.email, expiresAt: Date.now() + 86400000, createdAt: Date.now() }]));
 localStorage.setItem('visionary_session_token', 'learner-connection-qa');
 const data = { conversations: [], sessions: [], artifacts: [], resources: [], notifications: [], audit: [], preferences: { locale: 'en', interfaceLocale: 'en', bilingual: false, lowBandwidth: false, notifications: 'weekly', memory: true, voice: true }, subscription: { plan: 'Free', state: 'active', invoices: [], usage: 0, usageDay: '2026-09-27' }, legacyImported: false };
 localStorage.setItem('visionary_workspace_v2', JSON.stringify({ version: 2, people: [{ id: learner.id, email: learner.email, name: 'Aarav', ageBand: 'minor', roles: ['student'] }, { id: parent.id, email: parent.email, name: 'Anika', ageBand: 'adult', roles: ['parent'] }], workspaces: [{ id: 'demo-learner:student', personId: learner.id, role: 'student', name: 'Learner space', lastPath: '/dashboard/connections' }, { id: 'demo-parent:parent', personId: parent.id, role: 'parent', name: 'Parent space', lastPath: '/dashboard/connections' }], active: { [learner.id]: 'demo-learner:student', [parent.id]: 'demo-parent:parent' }, relationships: [{ id: 'parent-learner-pending', from: parent.id, to: learner.id, type: 'guardian', status: 'pending', scope: ['progress-summary'], expiresAt: new Date(Date.now() + 86400000).toISOString() }, { id: 'parent-learner-expired', from: parent.id, to: learner.id, type: 'teacher', status: 'pending', scope: ['shared-resources'], expiresAt: '2020-01-01T00:00:00Z' }], data: { 'demo-learner:student': data, 'demo-parent:parent': data } }));
})()`);
const learnerPage = await context.newPage();
learnerPage.on('pageerror', error => errors.push(String(error)));
await learnerPage.goto(`${base}/dashboard/connections`, { waitUntil: 'networkidle' });
await learnerPage.getByText('Needs your approval').waitFor();
await learnerPage.evaluate(() => {
 const original = Storage.prototype.setItem;
 let failOnce = true;
 Storage.prototype.setItem = function(key, value) {
  if (key === 'visionary_workspace_v2' && failOnce) { failOnce = false; throw new Error('Storage full'); }
  return original.call(this, key, value);
 };
});
await learnerPage.getByRole('button', { name: 'Accept' }).click();
await learnerPage.getByRole('alert').getByText(/could not be saved/).waitFor();
await learnerPage.getByText('Needs your approval').waitFor();
await learnerPage.getByRole('button', { name: 'Accept' }).click();
await learnerPage.getByRole('button', { name: 'Disconnect' }).waitFor();
await learnerPage.getByRole('button', { name: 'Disconnect' }).scrollIntoViewIfNeeded();
if (await learnerPage.evaluate(() => document.documentElement.scrollWidth - innerWidth) > 1) throw new Error('Learner connections overflow at 390px');
await learnerPage.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/learner-connections-mobile.png' });
const acceptedState = await context.storageState();
const parentContext = await browser.newContext({ storageState: acceptedState, viewport: { width: 390, height: 844 } });
await parentContext.addInitScript(() => localStorage.setItem('visionary_session_token', 'parent-connection-qa'));
const parentPage = await parentContext.newPage();
parentPage.on('pageerror', error => errors.push(String(error)));
await parentPage.goto(`${base}/dashboard/connections`, { waitUntil: 'networkidle' });
await parentPage.getByRole('heading', { name: 'Closed history' }).waitFor();
await parentPage.getByText('Expired', { exact: true }).waitFor();
await parentPage.getByRole('button', { name: 'Disconnect' }).waitFor();
await parentPage.getByRole('button', { name: 'Disconnect' }).scrollIntoViewIfNeeded();
if (await parentPage.evaluate(() => document.documentElement.scrollWidth - innerWidth) > 1) throw new Error('Parent connections overflow at 390px');
await parentPage.screenshot({ path: 'docs/visionary/baseline/design-2026-09-27/parent-connections-mobile.png' });
await parentPage.goto(`${base}/dashboard/reports?child=demo-learner`, { waitUntil: 'networkidle' });
await parentPage.getByRole('heading', { name: 'Aarav' }).waitFor();
await parentPage.goto(`${base}/dashboard/connections`, { waitUntil: 'networkidle' });
await parentPage.getByRole('button', { name: 'Disconnect' }).click();
await parentPage.getByText('Closed · revoked').waitFor();
await parentPage.goto(`${base}/dashboard/reports?child=demo-learner`, { waitUntil: 'networkidle' });
await parentPage.getByRole('heading', { name: 'This report is no longer shared' }).waitFor();
if (errors.length) throw new Error(`Connection center page errors: ${errors.join('; ')}`);
console.log('connections: learner accepted guardian scope, parent saw active and expired history, revoked access; 0 page errors');
await parentContext.close();
await context.close();
await browser.close();
